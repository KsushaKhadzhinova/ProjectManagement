def write_wbs_png():
    lines = [
        'digraph WBS {',
        '  graph [rankdir=TB, splines=ortho, nodesep=0.25, ranksep=0.5, fontname="Arial"];',
        '  node [shape=box, style="rounded,filled", fontname="Arial", fontsize=11];',
        '  edge [arrowhead=none];',
        '  root [label="0 NotaCode — MVP", fillcolor="#d9e2f3", fontsize=13];',
    ]
    for code, name, tasks in WBS:
        sid = 's' + code[0]
        lines.append(f'  {sid} [label="{code}\\n{name}", fillcolor="#e2efd9"];')
        lines.append(f'  root -> {sid};')
        prev = sid
        for tcode, tname in tasks:
            tid = 't' + tcode.replace('.', '_')
            wrapped = tname if len(tname) < 26 else tname[:tname.rfind(' ', 0, 26)] + '\\n' + tname[tname.rfind(' ', 0, 26) + 1:]
            lines.append(f'  {tid} [label="{tcode}\\n{wrapped}", fillcolor="#fff2cc", fontsize=9];')
            lines.append(f'  {prev} -> {tid};')
            prev = tid
    lines.append('}')
    with open(WBS_DOT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    subprocess.run(['dot', '-Tpng', '-Gdpi=160', WBS_DOT, '-o', WBS_PNG], check=True)


