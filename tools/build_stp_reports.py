def out_paths(lab, name):
    return os.path.join(lab, '07_результаты', f'{name}.docx')


def pic(lab, *parts):
    path = os.path.join(lab, *parts)
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    return path


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


